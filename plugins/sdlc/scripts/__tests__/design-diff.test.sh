#!/usr/bin/env bash
# design-diff.test.sh — pins design-diff.sh: a design revision compared with the base branch yields
# exactly the changed pages, component instances, images and inventory rows, with a
# Before | After | Diff PNG per visual change and one "## Changed in this revision" block in index.md.
#
# Renders with real Playwright (the repo's @playwright/test). CI installs it; locally, a worktree
# without node_modules borrows the primary checkout's. Unresolvable outside CI -> the render cases
# are skipped (said loudly); in CI that is a failure.
#
# Self-runnable, no test harness/framework dependency:
#   bash plugins/sdlc/scripts/__tests__/design-diff.test.sh
# Exit 0 = PASS (all cases), non-zero = FAIL (any case).
set -uo pipefail

here="${BASH_SOURCE[0]%/*}"; [ "$here" = "${BASH_SOURCE[0]}" ] && here="."
here="$(cd "$here" && pwd)"
script="$here/../design-diff.sh"
repo_root="$(cd "$here/../../../.." && pwd)"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

fail=0
ok()  { echo "PASS: $1"; }
bad() { echo "FAIL: $1 — $2" >&2; fail=1; }

export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t

resolve_pw() {
  local root
  for root in "$repo_root" "$(cd "$(git -C "$repo_root" rev-parse --git-common-dir)/.." && pwd)"; do
    node -e 'const p=require("path");console.log(p.dirname(require.resolve("@playwright/test/package.json",{paths:[process.argv[1]]})))' \
      "$root" 2>/dev/null && return 0
  done
  return 1
}
PW="$(resolve_pw)" || PW=""
if [ -z "$PW" ]; then
  if [ -n "${CI:-}" ]; then bad "playwright" "@playwright/test not resolvable in CI"; exit 1; fi
  echo "SKIP: render cases — @playwright/test not resolvable (run pnpm install)" >&2
fi

# --- fixture --------------------------------------------------------------------------------------
repo="$tmp/repo"; mkdir -p "$repo"; git -C "$repo" init -q -b main
D="$repo/docs/design/demo"; mkdir -p "$D/pages" "$D/screenshots"

page() { # page <file> <body>
  printf '<!doctype html><html><head><style>body{margin:0;font:16px sans-serif}button{margin:8px;padding:6px 12px}.card{margin:8px;padding:12px;border:1px solid #888;width:200px}</style></head><body>%s</body></html>' "$2" >"$D/pages/$1"
}
index() { # index <extra rows...>
  {
    echo "# Design — Demo"; echo
    echo "<!-- Generated by design-ingest.sh. Edit only the Description column; re-runs keep it by File. -->"; echo
    echo "| Kind | Title | File | Render | Description |"
    echo "|---|---|---|---|---|"
    for r in "$@"; do echo "$r"; done
  } >"$D/index.md"
}
components() { # components <rows...>
  {
    echo "Library: packages/ui/"; echo "Storybook: no"; echo
    echo "| Component | Status | Library export | Gap | Used in | Selector |"
    echo "|---|---|---|---|---|---|"
    for r in "$@"; do echo "$r"; done
  } >"$D/components.md"
}
png() { # png <out> <color> — a 120x80 solid image, drawn by the same browser the script uses
  node -e '
    const { chromium } = require(process.argv[1]);
    (async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 120, height: 80 } });
      await p.setContent(`<body style="margin:0;background:${process.argv[3]}"></body>`);
      await p.screenshot({ path: process.argv[2] }); await b.close(); })();' "$PW" "$1" "$2"
}

# v1 on the base branch
page a.html '<button data-slot="button">Save</button><button data-slot="button">Cancel</button><div class="card">Card body</div>'
page b.html '<button data-slot="button">One</button>'
page gone.html '<p>Removed later</p>'
printf 'body{}' >"$D/shared.css"
index '| page | a | pages/a.html | - | page a |' '| page | b | pages/b.html | - | page b |' \
      '| page | gone | pages/gone.html | - | gone |' '| screenshot | s | screenshots/s.png | - | shot |'
components '| Button | Reused | ui/button | — | pages/a.html, pages/b.html | |' \
           '| Card | Reused | ui/card | — | pages/a.html | `.card` |' \
           '| Ghost | Reused | ui/ghost | — | pages/a.html | |'
if [ -n "$PW" ]; then png "$D/screenshots/s.png" '#3366cc'; else printf 'v1' >"$D/screenshots/s.png"; fi
git -C "$repo" add -A && git -C "$repo" commit -qm v1

run() { (cd "$repo" && SDLC_PLAYWRIGHT="${1}" bash "$script" --base main docs/design/demo) 2>"$tmp/err"; }

# --- case 1: usage ------------------------------------------------------------------------------
(cd "$repo" && bash "$script" docs/design/demo >/dev/null 2>&1); rc=$?
[ "$rc" = "2" ] && ok "no --base exits 2" || bad "no --base exits 2" "rc=$rc"

# --- case 2: base has no such design -> diff=new, nothing written --------------------------------
mkdir -p "$repo/docs/design/fresh"; cp "$D/index.md" "$repo/docs/design/fresh/index.md"
out="$(cd "$repo" && SDLC_PLAYWRIGHT=none bash "$script" --base main docs/design/fresh)"
if [ "$out" = "SUMMARY rows=0 diff=new" ] && ! grep -q 'Changed in this revision' "$repo/docs/design/fresh/index.md"; then
  ok "first ingest -> diff=new, index untouched"
else bad "first ingest -> diff=new, index untouched" "$out"; fi
rm -rf "$repo/docs/design/fresh"

# --- case 3: unchanged design -> No changes (render is deterministic) ----------------------------
if [ -n "$PW" ]; then
  out="$(run "$PW")"
  if echo "$out" | grep -q '^SUMMARY rows=0 diff=playwright$' && grep -q '^No changes\.$' "$D/index.md" && [ -z "$(ls -A "$D/renders/diff" 2>/dev/null)" ]; then
    ok "unchanged design -> rows=0, No changes."
  else bad "unchanged design -> rows=0, No changes." "$out $(cat "$tmp/err")"; fi
  git -C "$repo" checkout -q -- . && rm -rf "$D/renders"
fi

# v2 in the working tree: Cancel -> Discard, b gains a button, gone removed, new added, shot recoloured,
# Card's inventory status changes, Chip appears (Selector none), Ghost never renders
page a.html '<button data-slot="button">Save</button><button data-slot="button">Discard changes</button><div class="card">Card body</div>'
page b.html '<button data-slot="button">One</button><button data-slot="button">Two</button>'
rm "$D/pages/gone.html"
page new.html '<p>New page</p>'
index '| page | a | pages/a.html | - | page a |' '| page | b | pages/b.html | - | page b |' \
      '| page | new | pages/new.html | - | new |' '| screenshot | s | screenshots/s.png | - | shot |'
components '| Button | Reused | ui/button | — | pages/a.html, pages/b.html | |' \
           '| Card | Changed | ui/card | header slot | pages/a.html | `.card` |' \
           '| Ghost | Reused | ui/ghost | glow state | pages/a.html | |' \
           '| Chip | New | — | label, removable | pages/new.html | none |' \
           '| Pill | New | — | label | pages/new.html | |'
printf 'body{color:red}' >"$D/shared.css"
if [ -n "$PW" ]; then png "$D/screenshots/s.png" '#cc3333'; else printf 'v2' >"$D/screenshots/s.png"; fi

has() { echo "$out" | grep -qF -- "$1"; }
check() { if has "$2"; then ok "$1"; else bad "$1" "missing '$2' in: $out $(cat "$tmp/err")"; fi; }
lacks() { if has "$2"; then bad "$1" "unexpected '$2' in: $out"; else ok "$1"; fi; }
ispng() { [ "$(head -c 8 "$1" 2>/dev/null | od -An -tx1 | tr -d ' \n')" = "89504e470d0a1a0a" ]; }

# --- case 4: the full revision -------------------------------------------------------------------
if [ -n "$PW" ]; then
  out="$(run "$PW")"
  check "changed page a"                 "DIFF changed page a pages/a.html"
  check "changed instance Button #2"     "DIFF changed component Button #2 pages/a.html"
  lacks "unchanged instance Button #1"   "Button #1 pages/a.html"
  lacks "unchanged Card instance"        "component Card pages/a.html"
  check "Button count 1→2 on b"          "DIFF count component Button pages/b.html 1→2"
  check "added page new"                 "DIFF added page new pages/new.html"
  check "removed page gone"              "DIFF removed page gone pages/gone.html"
  check "changed screenshot"             "DIFF changed screenshot s screenshots/s.png 100.0%"
  check "inventory status change"        "DIFF changed inventory Card - Reused→Changed"
  check "inventory new component"        "DIFF added inventory Chip - New"
  check "selector matched nowhere"       "UNCAPTURED Ghost"
  lacks "Selector none skips capture"    "UNCAPTURED Chip"
  lacks "added-page-only not uncaptured" "UNCAPTURED Pill"
  check "inventory Gap-only change"      "DIFF changed inventory Ghost - Gap"
  lacks "no asset rows with renders"     " asset "
  rev1="$(grep '^Revision:' "$D/index.md" | cut -d'`' -f2)"
  check "summary"                        "diff=playwright"
  for f in pages/pages_a.html.png components/Button--a--2.png screenshots/screenshots_s.png.png; do
    if ispng "$D/renders/diff/$f"; then ok "diff image $f"; else bad "diff image $f" "missing or not a PNG"; fi
  done
  row="$(grep -F '| changed | component | Button #2 |' "$D/index.md")"
  [ "$row" = "| changed | component | Button #2 | pages/a.html | $(echo "$out" | awk '/Button #2/ { print $NF }') | renders/diff/components/Button--a--2.png |" ] \
    && ok "index row names its diff image" || bad "index row names its diff image" "$row"
  [ "$(grep -c '^## Changed in this revision$' "$D/index.md")" = "1" ] && ok "one Changed block" || bad "one Changed block" "$(cat "$D/index.md")"
  grep -qF '| page | a | pages/a.html | - | page a |' "$D/index.md" && ok "asset table kept" || bad "asset table kept" "$(cat "$D/index.md")"

  # --- case 5: re-run replaces the block, never stacks it; stale diff images go -------------------
  mkdir -p "$D/renders/diff/pages" && printf 'stale' >"$D/renders/diff/pages/stale.png"
  out="$(run "$PW")"
  [ "$(grep -c '^## Changed in this revision$' "$D/index.md")" = "1" ] && ok "re-run keeps one block" || bad "re-run keeps one block" "$(cat "$D/index.md")"
  rev2="$(grep '^Revision:' "$D/index.md" | cut -d'`' -f2)"
  [ -n "$rev1" ] && [ "$rev1" = "$rev2" ] && ok "same change -> same Revision" || bad "same change -> same Revision" "'$rev1' vs '$rev2'"

  # --- case 5b: a design-ingest re-run never takes Changed rows into the asset table ------------
  printf '<p>x</p>' >"$tmp/extra.html"
  SDLC_DESIGN_BROWSER=none bash "$here/../design-ingest.sh" "$D" "$tmp/extra.html" >/dev/null 2>&1
  if grep -qE '^\| (changed|added|removed|count) \|' "$D/index.md"; then bad "ingest drops Changed rows" "$(cat "$D/index.md")"
  else ok "ingest drops Changed rows"; fi
  git -C "$repo" checkout -q -- docs/design/demo/index.md && rm -f "$D/pages/extra.html"
  index '| page | a | pages/a.html | - | page a |' '| page | b | pages/b.html | - | page b |' \
        '| page | new | pages/new.html | - | new |' '| screenshot | s | screenshots/s.png | - | shot |'

  # --- case 5c: Playwright found without SDLC_PLAYWRIGHT (repo node_modules) --------------------
  mkdir -p "$repo/node_modules/@playwright" && ln -s "$PW" "$repo/node_modules/@playwright/test"
  out="$(run "")"
  check "auto-discovered Playwright" "diff=playwright"
  rm -rf "$repo/node_modules"
  [ ! -e "$D/renders/diff/pages/stale.png" ] && ok "stale diff images removed" || bad "stale diff images removed" "still there"
fi

# --- case 6: no Playwright -> byte compare still names every changed file -------------------------
rm -rf "$D/renders"
out="$(run none)"
check "fallback: changed page a"       "DIFF changed page a pages/a.html -"
check "fallback: added page new"       "DIFF added page new pages/new.html -"
check "fallback: removed page gone"    "DIFF removed page gone pages/gone.html -"
check "fallback: changed screenshot"   "DIFF changed screenshot s screenshots/s.png -"
check "fallback: inventory rows kept"  "DIFF changed inventory Card - Reused→Changed"
check "fallback: summary"              "diff=disabled"
check "fallback: shared asset row"     "DIFF changed asset shared.css shared.css -"
lacks "fallback: no capture rows"      "UNCAPTURED"
[ ! -d "$D/renders/diff" ] && ok "fallback: no images" || bad "fallback: no images" "renders/diff exists"

# --- case 7: unknown base ref is an error, never a silent first ingest ---------------------------
(cd "$repo" && SDLC_PLAYWRIGHT=none bash "$script" --base origin/nope docs/design/demo >/dev/null 2>&1); rc=$?
[ "$rc" = "1" ] && ok "unknown base ref exits 1" || bad "unknown base ref exits 1" "rc=$rc"

# --- case 8: base design had no components.md -> components are added, never removed -------------
repo2="$tmp/repo2"; mkdir -p "$repo2/d"; git -C "$repo2" init -q -b main
printf '| Kind | Title | File | Render | Description |\n|---|---|---|---|---|\n' >"$repo2/d/index.md"
git -C "$repo2" add -A && git -C "$repo2" commit -qm v1
printf '| Component | Status | Library export | Gap | Used in |\n|---|---|---|---|---|\n| Button | Reused | ui/button | — | - |\n' >"$repo2/d/components.md"
out="$(cd "$repo2" && SDLC_PLAYWRIGHT=none bash "$script" --base main d 2>&1)"
check "no old inventory: added"   "DIFF added inventory Button - Reused"
lacks "no old inventory: removed" "removed inventory"

[ "$fail" = "0" ] && echo "design-diff.test.sh: PASS" || echo "design-diff.test.sh: FAIL" >&2
exit "$fail"
